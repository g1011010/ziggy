// Bundles the app's static files into worker/site.js so the Cloudflare Worker
// can serve them without a separate asset upload. Run automatically by
// `wrangler deploy` / `wrangler dev` (see "build" in wrangler.jsonc).

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const INCLUDE = ['index.html', 'manifest.webmanifest', 'sw.js', 'css', 'js', 'vendor', 'icons'];
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.webmanifest': 'application/manifest+json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
};

function walk(p) {
  const full = join(ROOT, p);
  if (statSync(full).isDirectory()) return readdirSync(full).flatMap((f) => walk(join(p, f)));
  return TYPES[extname(p)] ? [p] : [];
}

const files = {};
let total = 0;
for (const p of INCLUDE.flatMap(walk)) {
  const buf = readFileSync(join(ROOT, p));
  total += buf.length;
  files['/' + relative('.', p).split('\\').join('/')] = {
    type: TYPES[extname(p)],
    etag: '"' + createHash('sha1').update(buf).digest('hex').slice(0, 16) + '"',
    b64: buf.toString('base64'),
  };
}

writeFileSync(
  join(ROOT, 'worker/site.js'),
  '// Generated by scripts/build-worker.mjs — do not edit.\n' +
  `export const FILES = ${JSON.stringify(files)};\n`,
);
console.log(`worker/site.js: ${Object.keys(files).length} files, ${(total / 1024).toFixed(0)} KiB`);
